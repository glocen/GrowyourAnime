"""Turn an art sheet's frame table (the asset maker's <effect>_art.json) into a Luau module the game plays it by.

    py tools/art/art_table.py build/handoff/Shade/fx/shade_burst_art.json src/shared/Config/ShadeBurstArt.luau "AR2, section 11"

The table lists, for each of the clip's frames, every picture on screen: its kind, its centre in studs, its size, its
rectangle in the sheet, its rotation and its width's squeeze. A kind drawn once a frame (a flame) keeps id 1. A kind with
several (paper scraps) is listed in a stable order while all of them live, and ends out of order: each picture is matched
to the last frame's of its kind in the same sheet row (each scrap burns along its own row), at the least distance, so one
scrap keeps one id from its first frame to its last. The module is generated: run this again on a new delivery, never edit
it by hand.
"""

import itertools
import json
import sys
from pathlib import Path


def number(value: float) -> str:
    text = f"{value:.3f}".rstrip("0").rstrip(".")
    return "0" if text in ("-0", "") else text


def assign_ids(frames: dict[int, list[dict]]) -> None:
    last: dict[str, list[dict]] = {}
    next_id: dict[str, int] = {}
    for frame in sorted(frames):
        by_kind: dict[str, list[dict]] = {}
        for picture in frames[frame]:
            by_kind.setdefault(picture["what"], []).append(picture)
        for kind, pictures in by_kind.items():
            before = last.get(kind, [])
            if len(before) >= len(pictures) and before:
                best = None
                for chosen in itertools.permutations(range(len(before)), len(pictures)):
                    if any(before[b]["rect"][1] != pictures[j]["rect"][1] for j, b in enumerate(chosen)):
                        continue
                    cost = sum(
                        sum((x - y) ** 2 for x, y in zip(before[b]["at"], pictures[j]["at"])) for j, b in enumerate(chosen)
                    )
                    if best is None or cost < best[0]:
                        best = (cost, chosen)
                if best is None:
                    raise SystemExit(f"frame {frame}: no match for the {kind} pictures in their rows")
                for j, b in enumerate(best[1]):
                    pictures[j]["id"] = before[b]["id"]
            else:
                for picture in pictures:
                    next_id[kind] = next_id.get(kind, 0) + 1
                    picture["id"] = next_id[kind]
            last[kind] = pictures
        for kind in list(last):
            if kind not in by_kind:
                del last[kind]


def main() -> None:
    if len(sys.argv) != 4:
        raise SystemExit(__doc__)
    source, out, where = Path(sys.argv[1]), Path(sys.argv[2]), sys.argv[3]
    table = json.loads(source.read_text(encoding="utf-8"))
    frames = {int(k): v for k, v in table["frames"].items()}
    assign_ids(frames)
    first, last = min(frames), max(frames)
    lines = [
        "--!strict",
        f"-- {out.stem}: the art sheet's frame table ({where}), generated by tools/art/art_table.py from",
        f"-- {source.as_posix()}. Don't edit it: run the tool again on a new delivery.",
        f"-- Frames are the clip's, {table['fps']} a second; Burst is its marker's frame. Each picture: its Kind, its Id (one picture",
        "-- keeps one id from its first frame to its last), At its centre in studs (" + table["axes"] + "),",
        "-- Size in studs, its rectangle in the picture (Offset, Rect, pixels), Rotation in degrees, and Squash, its width's share.",
        "",
        "export type Picture = {",
        "\tKind: string,",
        "\tId: number,",
        "\tAt: Vector3,",
        "\tSize: Vector2,",
        "\tOffset: Vector2,",
        "\tRect: Vector2,",
        "\tRotation: number,",
        "\tSquash: number,",
        "}",
        "",
        "local function p(kind: string, id: number, x: number, y: number, z: number, w: number, h: number, ox: number, oy: number, rw: number, rh: number, rotation: number, squash: number): Picture",
        "\treturn {",
        "\t\tKind = kind,",
        "\t\tId = id,",
        "\t\tAt = Vector3.new(x, y, z),",
        "\t\tSize = Vector2.new(w, h),",
        "\t\tOffset = Vector2.new(ox, oy),",
        "\t\tRect = Vector2.new(rw, rh),",
        "\t\tRotation = rotation,",
        "\t\tSquash = squash,",
        "\t}",
        "end",
        "",
        "return {",
        f"\tSize = Vector2.new({table['size'][0]}, {table['size'][1]}), -- the picture, pixels",
        f"\tBurst = {table['burst']},",
        f"\tFirst = {first},",
        f"\tLast = {last},",
        f"\tCollar = Vector3.new({', '.join(number(v) for v in table['collar_at_burst'])}), -- where the sheet's collar stood at the Burst (the Torso's, 1.5 up it), from its feet",
        "\tFrames = {",
    ]
    for frame in range(first, last + 1):
        pictures = frames.get(frame, [])
        lines.append(f"\t\t[{frame}] = {{")
        for e in pictures:
            values = [*e["at"], *e["size"], *e["rect"], e["rotation"], e["squash"]]
            lines.append(f'\t\t\tp("{e["what"]}", {e["id"]}, ' + ", ".join(number(v) for v in values) + "),")
        lines.append("\t\t},")
    lines += ["\t} :: { [number]: { Picture } },", "}", ""]
    out.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"{out}: frames {first} to {last}, {sum(len(v) for v in frames.values())} pictures")


if __name__ == "__main__":
    main()
